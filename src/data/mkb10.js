const CUSTOM_KEY = 'medconsult_mkb10_custom'

export function getCustomCodes() {
  try {
    return JSON.parse(_ls().getItem(CUSTOM_KEY) || '[]')
  } catch {
    return []
  }
}

export function addCustomCode(code, label) {
  const list = getCustomCodes()
  list.push({ code: code.trim(), label: label.trim() })
  _ls().setItem(CUSTOM_KEY, JSON.stringify(list))
}

export function removeCustomCode(code) {
  const list = getCustomCodes().filter((c) => c.code !== code)
  _ls().setItem(CUSTOM_KEY, JSON.stringify(list))
}

export function getAllMkb10() {
  return [...MKB10_SEED, ...getCustomCodes()]
}

export function searchMkb10(query) {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return getAllMkb10()
    .filter((c) => c.code.toLowerCase().includes(q) || c.label.toLowerCase().includes(q))
    .slice(0, 15)
}

// Достаём коды вида N40, N41.1, C61 из произвольного текста диагноза —
// используется, чтобы понять, для каких кодов искать клинические рекомендации.
export function extractCodesFromText(text) {
  if (!text) return []
  const matches = text.match(/\b[A-Z]\d{2}(\.\d+)?\b/g) || []
  return [...new Set(matches.map((c) => c.toUpperCase()))]
}
